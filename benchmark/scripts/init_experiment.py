#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import random
import shutil
from pathlib import Path

ARMS = ["baseline", "kernel", "skill", "selective"]
TASK_CLASSES = ["small", "medium", "large", "risky"]
RISK_LEVELS = {
    "small": "low",
    "medium": "medium",
    "large": "high",
    "risky": "critical",
}


def build_manifest(experiment_id: str, stage: str, task_count: int, replicates: int, seed: int) -> dict:
    rng = random.Random(seed)
    tasks = []
    arm_orders: dict[str, list[str]] = {}

    for index in range(1, task_count + 1):
        task_id = f"task-{index:02d}"
        task_class = TASK_CLASSES[(index - 1) % len(TASK_CLASSES)]
        tasks.append(
            {
                "task_id": task_id,
                "title": f"REPLACE_ME task {index:02d}",
                "task_class": task_class,
                "risk_level": RISK_LEVELS[task_class],
                "prompt_path": f"tasks/{task_id}.md",
                "fixture_commit": "REPLACE_ME",
                "replicates": replicates,
                "deliverables": ["REPLACE_ME"],
                "acceptance_checks": ["REPLACE_ME"],
            }
        )
        for replicate in range(1, replicates + 1):
            order = ARMS.copy()
            rng.shuffle(order)
            arm_orders[f"{task_id}:r{replicate}"] = order

    return {
        "schema_version": "1.0",
        "experiment_id": experiment_id,
        "stage": stage,
        "implementation_commit": "REPLACE_ME",
        "random_seed": seed,
        "arms": ARMS,
        "primary_outcomes": ["task_success", "deterministic_score", "total_tokens"],
        "analysis_command": (
            f"python3 benchmark/scripts/analyze.py benchmark/experiments/{experiment_id}/run-records.jsonl "
            f"--manifest benchmark/experiments/{experiment_id}/manifest.json "
            f"--output benchmark/experiments/{experiment_id}/report.md"
        ),
        "exclusion_rules": [
            {
                "code": "HOST_CRASH_BEFORE_MODEL",
                "description": "The host crashed before the first model invocation.",
            },
            {
                "code": "AUTHENTICATION_FAILURE",
                "description": "Authentication failed before the first model invocation.",
            },
            {
                "code": "FIXTURE_SETUP_FAILURE",
                "description": "The clean fixture could not be created before the run.",
            },
        ],
        "settings": {
            "host": "REPLACE_ME",
            "host_version": "REPLACE_ME",
            "provider": "REPLACE_ME",
            "model": "REPLACE_ME",
            "effort": None,
            "temperature": None,
            "permission_mode": "REPLACE_ME",
            "tool_profile": "REPLACE_ME",
            "environment_id": "REPLACE_ME",
            "timeout_seconds": 900,
        },
        "arm_orders": arm_orders,
        "tasks": tasks,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Create a Mero Precision benchmark experiment skeleton")
    parser.add_argument("directory", type=Path)
    parser.add_argument("--experiment-id", required=True)
    parser.add_argument("--tasks", type=int, default=12)
    parser.add_argument("--replicates", type=int, default=1)
    parser.add_argument("--seed", type=int, default=20260824)
    parser.add_argument("--stage", choices=["pilot", "claim-candidate"], default="pilot")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()

    if args.tasks < 1:
        parser.error("--tasks must be at least 1")
    if args.replicates < 1:
        parser.error("--replicates must be at least 1")

    target = args.directory.resolve()
    if target.exists() and any(target.iterdir()):
        if not args.force:
            parser.error(f"directory is not empty: {target}")
        shutil.rmtree(target)

    target.mkdir(parents=True, exist_ok=True)
    (target / "tasks").mkdir()
    (target / "raw").mkdir()
    (target / "raw/.gitkeep").write_text("", encoding="utf-8")
    (target / "run-records.jsonl").write_text("", encoding="utf-8")

    manifest = build_manifest(args.experiment_id, args.stage, args.tasks, args.replicates, args.seed)
    (target / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    for task in manifest["tasks"]:
        prompt = (
            f"# {task['title']}\n\n"
            "Replace this file with the exact task prompt before preregistration.\n\n"
            "## Required deliverables\n\n- REPLACE_ME\n\n"
            "## Acceptance checks\n\n- REPLACE_ME\n"
        )
        (target / task["prompt_path"]).write_text(prompt, encoding="utf-8")

    readme = (
        f"# {args.experiment_id}\n\n"
        "This directory was generated by `benchmark/scripts/init_experiment.py`.\n\n"
        "Before the preregistration commit:\n\n"
        "1. Replace all `REPLACE_ME` values.\n"
        "2. Write the exact prompts.\n"
        "3. Verify every acceptance check against the clean fixture.\n"
        "4. Confirm the randomized arm order.\n"
        "5. Commit this directory.\n"
        "6. Put that commit hash in every run record.\n"
    )
    (target / "README.md").write_text(readme, encoding="utf-8")

    print(f"created experiment skeleton: {target}")
    print("replace every REPLACE_ME value, then commit before running any arm")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
